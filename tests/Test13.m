let
    proj=mgis[proj],ops=mgis[gisLayerQueryOperators],
    wgs=proj[fromEPSG][#"EPSG:4326"],utm=proj[fromProj4]("+proj=utm +zone=31 +datum=WGS84 +units=m"),
    web=proj[fromEPSG][#"EPSG:3857"],feet=proj[fromProj4]("+proj=merc +datum=WGS84 +units=ft"),
    shape=mgis[gisShapeCreateFromWKT],buffer=mgis[gisShapeCreateBuffer],layerBuffer=mgis[gisLayerCreateBuffer],
    layer=(wkt,crs)=>mgis[gisLayerCreateFromTableWithWKT](#table({"Name","geom"},{{"Retained",wkt}}),"geom",crs),
    inside=(s,x,y)=>not List.IsEmpty(ops[gisContains][onCandidate](s,shape("POINT(" & Text.From(x,"en-US") & " " & Text.From(y,"en-US") & ")"))),
    area=(g)=>if g[Kind]="MULTIPOLYGON" then List.Sum(List.Transform(g[Components],each @area(_))) else
        List.Sum(List.Transform(g[Rings],(r)=>let p=r[Points] in List.Sum(List.Transform(List.Skip(List.Positions(p)),
            (i)=>p{i-1}[X]*p{i}[Y]-p{i}[X]*p{i-1}[Y]))/2)),
    point=buffer(shape("POINT(0 0)"),10,[resolution=32]),
    line=buffer(shape("LINESTRING(0 0,20 0)"),2,[resolution=32]),
    bend=buffer(shape("LINESTRING(0 0,10 0,10 10)"),2,[resolution=32]),
    square=buffer(shape("POLYGON((0 0,10 0,10 10,0 10,0 0))"),2,[resolution=32]),
    reversed=buffer(shape("POLYGON((0 0,0 10,10 10,10 0,0 0))"),2,[resolution=32]),
    concave=buffer(shape("POLYGON((0 0,10 0,10 2,2 2,2 10,0 10,0 0))"),1,[resolution=32]),
    holed=shape("POLYGON((0 0,20 0,20 20,0 20,0 0),(5 5,15 5,15 15,5 15,5 5))"),
    hole=buffer(holed,2,[resolution=32]),filled=buffer(holed,6,[resolution=32]),
    separated=buffer(shape("MULTIPOINT((0 0),(20 0))"),2,[resolution=32]),
    overlapping=buffer(shape("MULTIPOINT((0 0),(3 0))"),2,[resolution=32]),
    touching=buffer(shape("MULTIPOINT((0 0),(4 0))"),2,[resolution=32]),
    twinHoles=buffer(shape("MULTIPOLYGON(((0 0,20 0,20 20,0 20,0 0),(5 5,15 5,15 15,5 15,5 5)),((40 0,60 0,60 20,40 20,40 0),(45 5,55 5,55 15,45 15,45 5)))"),2,[resolution=32]),
    crossing=buffer(shape("LINESTRING(0 0,10 10,0 10,10 0)"),1,[resolution=32]),
    closedLine=buffer(shape("LINESTRING(0 0,10 0,10 10,0 10,0 0)"),1,[resolution=32]),
    retraced=buffer(shape("LINESTRING(0 0,10 0,0 0,10 0)"),1,[resolution=32]),
    collection=buffer(shape("GEOMETRYCOLLECTION(POINT(0 0),LINESTRING(20 0,30 0),POLYGON((40 0,45 0,45 5,40 5,40 0)))"),1),
    projected=layerBuffer(layer("POINT(448352.001375365 5411954.90994727)",utm),10,"m",[resolution=32]),
    geographic=mgis[gisLayerCreateFromTableWithXY](#table({"Name","Longitude","Latitude"},{{"A",2.2945,48.8584}}),"Longitude","Latitude",wgs),
    example=mgis[gisLayerJoinSpatial](geographic,projected,ops[gisContains],"Left Outer"),
    geographicBuffer=layerBuffer(geographic,10,"m",[analysisCRS=utm,resolution=32]),
    matched=mgis[gisLayerJoinSpatial](geographic,geographicBuffer,ops[gisContains],"Inner"),
    footBuffer=layerBuffer(layer("POINT(0 0)",feet),1,"m",[resolution=32]),
    unnamed=layerBuffer(layer("POINT(0 0)",null),10,null,[resolution=32]),
    empty=layerBuffer(mgis[gisLayerCreateBlank]("geom",10,web),10,"m"),
    checks=[
        PointRadius=point[Envelope]=[MinX=-10,MinY=-10,MaxX=10,MaxY=10],
        PointCircle=Number.Abs(area(point[Geometry])-32*100*Number.Sin(2*Number.PI/32)/2)<1e-8,
        DefaultResolution=List.Count(buffer(shape("POINT(0 0)"),10)[Geometry][Rings]{0}[Points])=6,
        ResolutionLimits=List.AllTrue(List.Transform({3,5,32,100},(n)=>List.Count(buffer(shape("POINT(0 0)"),1,[resolution=n])[Geometry][Rings]{0}[Points])=n+1)),
        LineRoundCaps=inside(line,-1,0) and inside(line,10,1.9) and not inside(line,-1.9,1.9)
            and Number.Abs(area(line[Geometry])-(80+32*4*Number.Sin(2*Number.PI/32)/2))<1e-7,
        BendDissolved=bend[Kind]="POLYGON" and List.Count(bend[Geometry][Rings])=1 and inside(bend,9,1) and not inside(bend,6,6),
        PolygonRoundCorners=inside(square,-1,5) and inside(square,5,5) and not inside(square,-1.9,-1.9)
            and Number.Abs(area(square[Geometry])-(100+80+32*4*Number.Sin(2*Number.PI/32)/2))<1e-7,
        RingOrientation=Number.Abs(area(square[Geometry])-area(reversed[Geometry]))<1e-7,
        ConcavityPreserved=inside(concave,2.5,5) and not inside(concave,5,5),
        HoleShrinks=List.Count(hole[Geometry][Rings])=2 and inside(hole,6,10) and not inside(hole,10,10),
        HoleCloses=List.Count(filled[Geometry][Rings])=1 and inside(filled,10,10),
        DisconnectedParts=separated[Kind]="MULTIPOLYGON" and List.Count(separated[Geometry][Components])=2,
        OverlappingPartsDissolved=overlapping[Kind]="POLYGON" and List.Count(overlapping[Geometry][Rings])=1 and inside(overlapping,1.5,0),
        TouchingParts=touching[Kind]="MULTIPOLYGON" and List.Count(touching[Geometry][Components])=2,
        EqualAreaShellHoles=twinHoles[Kind]="MULTIPOLYGON" and List.AllTrue(List.Transform(twinHoles[Geometry][Components],each List.Count([Rings])=2))
            and not inside(twinHoles,10,10) and not inside(twinHoles,50,10),
        SelfCrossingLine=crossing[Kind]="POLYGON" and inside(crossing,5,5) and not inside(crossing,5,8),
        ClosedLineHole=List.Count(closedLine[Geometry][Rings])=2 and not inside(closedLine,5,5),
        RetracedLine=retraced[Kind]="POLYGON" and inside(retraced,5,0) and List.Count(retraced[Geometry][Rings])=1,
        OddResolutionLine=buffer(shape("LINESTRING(0 0,10 3,0 7)"),1,[resolution=5])[Kind]="POLYGON",
        MinimumResolutionPolygon=buffer(shape("POLYGON((0 0,10 0,10 10,0 10,0 0))"),1,[resolution=3])[Kind]="POLYGON",
        MaximumResolutionLine=buffer(shape("LINESTRING(0 0,10 0)"),1,[resolution=100])[Kind]="POLYGON",
        MixedCollection=collection[Kind]="MULTIPOLYGON" and List.Count(collection[Geometry][Components])=3,
        RepeatedVertices=Number.Abs(area(buffer(shape("LINESTRING(0 0,0 0,20 0,20 0)"),2,[resolution=32])[Geometry])-area(line[Geometry]))<1e-7,
        DegenerateLine=buffer(shape("LINESTRING(0 0,0 0)"),2)[Kind]="POLYGON",
        LayerMetadata=projected[geometryColumn]="geom" and projected[TProjection]=utm and projected[table]{0}[Name]="Retained"
            and projected[table]{0}[geom][__rowid__]=projected[table]{0}[__rowid__],
        SpatialIndexRebuilt=Table.RowCount(mgis[gisLayerQuerySpatial](projected,shape("POINT(448352 5411954.9)"),ops[gisContains])[table])=1,
        OriginalExampleOutside10m=example[table]{0}[layer2]=null,
        GeographicAnalysis=geographicBuffer[TProjection]=utm and Table.RowCount(matched[table])=1
            and geographicBuffer[table]{0}[Longitude]=2.2945,
        MetresInFootCRS=Number.Abs(footBuffer[table]{0}[geom][Envelope][MaxX]-1/0.3048)<1e-10,
        Kilometres=layerBuffer(layer("POINT(0 0)",web),0.01,"km",[resolution=32])[table]{0}[geom][Envelope][MaxX]=10,
        UndeclaredCoordinateUnits=unnamed[TProjection]=null and unnamed[table]{0}[geom][Envelope][MaxX]=10,
        EmptyLayer=Table.RowCount(empty[table])=0 and empty[TProjection]=web and empty[geometryColumn]="geom",
        InvalidDistance=List.AllTrue(List.Transform({0,-1,#nan,#infinity},each (try layerBuffer(layer("POINT(0 0)",web),_,"m"))[HasError])),
        SubPrecisionDistanceRejected=(try buffer(shape("POINT(100000000000000000000 100000000000000000000)"),1))[HasError],
        CoordinateOverflowRejected=(try buffer(mgis[gisShapeCreateFromGeoJSONRecord]([type="Point",coordinates={1e308,1e308}]),1e308))[HasError],
        InvalidResolution=List.AllTrue(List.Transform({2,101,3.5,#nan,#infinity},each (try layerBuffer(layer("POINT(0 0)",web),10,"m",[resolution=_]))[HasError])),
        EmptyInvalidResolution=(try layerBuffer(mgis[gisLayerCreateBlank]("geom",10,web),10,"m",[resolution=2]))[HasError],
        InvalidUnit=(try layerBuffer(layer("POINT(0 0)",web),10,"degree"))[HasError],
        UndeclaredUnitRejected=(try layerBuffer(layer("POINT(0 0)",null),10,"m"))[HasError],
        GeographicWithoutAnalysisRejected=(try layerBuffer(geographic,10,"m"))[HasError],
        GeographicAnalysisRejected=(try layerBuffer(layer("POINT(0 0)",web),10,"m",[analysisCRS=wgs]))[HasError]
    ],
    evaluated=Record.FromList(List.Transform(Record.FieldNames(checks),(name)=>let result=try Record.Field(checks,name)
        in if result[HasError] then result[Error][Message] else result[Value]),Record.FieldNames(checks))
in
    if List.AllTrue(List.Transform(Record.FieldValues(evaluated),each _=true)) then evaluated
    else error Error.Record("TestFailure",Text.FromBinary(Json.FromValue(evaluated)),null)
